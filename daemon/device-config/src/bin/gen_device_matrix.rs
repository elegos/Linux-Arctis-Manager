/// lam-gen-device-matrix — regenerates `docs/device_compatibility.md` from
/// the leaf files (anything not `base_*`) in `daemon/device-configs/`.
///
/// Each leaf file's `device.capabilities` list is the source of truth for
/// what's actually implemented — kept next to the structs/apis it describes,
/// so it can't drift the way a hand-maintained table does. This tool only
/// renders it; per-device known gaps stay in `docs/v3-backlog.md`, which
/// already tracks them in far more detail than a table cell could hold.
///
/// Usage:
///   lam-gen-device-matrix            regenerate the file in place
///   lam-gen-device-matrix --check    exit 1 if the committed file is stale
///                                    (used by CI — see rust-ci.yaml)
use std::path::{Path, PathBuf};

use device_config::{load, DeviceConfig};

fn main() {
    let check_only = std::env::args().any(|a| a == "--check"); // nosemgrep: rust.lang.security.args.args — build-time CI tool flag, not a security boundary

    let daemon_dir = Path::new(env!("CARGO_MANIFEST_DIR")).parent().unwrap();
    let configs_dir = daemon_dir.join("device-configs");
    let out_path = daemon_dir
        .parent()
        .unwrap()
        .join("docs/device_compatibility.md");

    let generated = generate(&configs_dir);

    if check_only {
        let existing = std::fs::read_to_string(&out_path).unwrap_or_default();
        if existing != generated {
            eprintln!(
                "{} is stale.\nRun `cargo run -p device-config --bin lam-gen-device-matrix` and commit the result.",
                out_path.display()
            );
            std::process::exit(1);
        }
        println!("{} is up to date.", out_path.display());
    } else {
        std::fs::write(&out_path, &generated)
            .unwrap_or_else(|e| panic!("failed to write {}: {e}", out_path.display()));
        println!("Wrote {}", out_path.display());
    }
}

fn generate(configs_dir: &Path) -> String {
    let mut leaf_paths: Vec<PathBuf> = std::fs::read_dir(configs_dir)
        .unwrap_or_else(|e| panic!("failed to read {}: {e}", configs_dir.display()))
        .filter_map(|e| e.ok())
        .map(|e| e.path())
        .filter(|p| {
            p.extension().is_some_and(|ext| ext == "yaml")
                && !p
                    .file_name()
                    .and_then(|n| n.to_str())
                    .is_some_and(|n| n.starts_with("base_"))
        })
        .collect();
    leaf_paths.sort();

    let mut rows: Vec<(String, String, Vec<String>)> = leaf_paths
        .iter()
        .map(|path| {
            let cfg: DeviceConfig = load(path, &[configs_dir])
                .unwrap_or_else(|e| panic!("failed to load {}: {e}", path.display()));
            let device = cfg.device.unwrap_or_else(|| {
                panic!("{} has no `device:` section", path.display());
            });
            let name = device
                .name
                .unwrap_or_else(|| path.file_stem().unwrap().to_string_lossy().into_owned());
            let pids = device
                .variants
                .unwrap_or_default()
                .iter()
                .map(|v| format!("`{:#06X}`", v.product_id))
                .collect::<Vec<_>>()
                .join(", ");
            let mut capabilities = device.capabilities.unwrap_or_default();
            capabilities.sort();
            (name, pids, capabilities)
        })
        .collect();
    rows.sort_by(|a, b| a.0.cmp(&b.0));

    let mut out = String::new();
    out.push_str("# Device compatibility matrix\n\n");
    out.push_str(
        "<!-- AUTO-GENERATED by `cargo run -p device-config --bin lam-gen-device-matrix`. -->\n\
         <!-- Do not edit by hand — CI fails if this drifts from the YAML in daemon/device-configs/. -->\n\n",
    );
    out.push_str(
        "Devices below are the ones with a working v3 (Rust daemon) configuration \
         file. Each row is generated straight from that device's `device.capabilities` \
         list, so it can't go stale independently of the code.\n\n",
    );
    out.push_str(
        "For per-device known gaps (what's modelled but not yet wired up, what's \
         still unconfirmed against real hardware, and what's not started), see \
         [`v3-backlog.md`](v3-backlog.md).\n\n",
    );
    out.push_str("| Device | Product ID(s) | Capabilities |\n");
    out.push_str("|---|---|---|\n");
    for (name, pids, capabilities) in &rows {
        let capabilities_cell = if capabilities.is_empty() {
            "—".to_string()
        } else {
            capabilities.join(", ")
        };
        out.push_str(&format!("| {name} | {pids} | {capabilities_cell} |\n"));
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn write(dir: &Path, name: &str, contents: &str) {
        std::fs::write(dir.join(name), contents).unwrap();
    }

    #[test]
    fn generate_lists_leaf_devices_sorted_by_name_skips_base_files() {
        let tmp = tempfile::tempdir().unwrap();
        write(
            tmp.path(),
            "zzz_device.yaml",
            "device:\n  name: \"Z Device\"\n  variants:\n    - product_id: 0x0002\n  capabilities: [battery]\n",
        );
        write(
            tmp.path(),
            "aaa_device.yaml",
            "device:\n  name: \"A Device\"\n  variants:\n    - product_id: 0x0001\n  capabilities: [chatmix, battery]\n",
        );
        write(
            tmp.path(),
            "base_shared.yaml",
            "device:\n  name: \"Should never appear\"\n  variants: []\n",
        );

        let out = generate(tmp.path());
        let a_line = out.lines().find(|l| l.contains("A Device")).unwrap();
        let z_line = out.lines().find(|l| l.contains("Z Device")).unwrap();
        assert!(
            !out.contains("Should never appear"),
            "base_ file must be skipped"
        );
        assert!(
            out.find(a_line).unwrap() < out.find(z_line).unwrap(),
            "rows sorted by device name"
        );
        assert!(a_line.contains("`0x0001`"));
        assert!(a_line.contains("battery, chatmix"), "capabilities sorted");
    }

    #[test]
    fn generate_renders_dash_for_no_capabilities() {
        let tmp = tempfile::tempdir().unwrap();
        write(
            tmp.path(),
            "bare.yaml",
            "device:\n  name: \"Bare\"\n  variants:\n    - product_id: 0x0003\n",
        );
        let out = generate(tmp.path());
        let line = out.lines().find(|l| l.contains("Bare")).unwrap();
        assert!(line.ends_with("| — |"));
    }
}
